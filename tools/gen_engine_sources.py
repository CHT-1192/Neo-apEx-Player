#!/usr/bin/env python3
"""Regenerate cmake/engine_sources.cmake from the vendored apEx tree.

The player compiles the original apEx engine nearly unchanged; only the
Windows-only translation units listed below are dropped, each replaced by a
portable implementation under src/ or excluded because the feature is not
available off Windows.  Keeping this in one place makes the exclusions
auditable and keeps CMakeLists.txt readable.
"""
import os

TP = "third_party/apEx"

EXCLUDE = {
    # --- platform code with a portable replacement -----------------------
    f"{TP}/Bedrock/BaseLib/CrashTracker.cpp": "walks the Windows TEB/PEB",
    f"{TP}/Bedrock/BaseLib/Socket.cpp": "WinSock only",
    f"{TP}/Bedrock/BaseLib/StackTracker.cpp": "DbgHelp; -> src/platform/stacktracker_posix.cpp",
    f"{TP}/Bedrock/BaseLib/ImageDecompressor.cpp": "OLE/GDI+; -> src/platform/image_stb.cpp",
    f"{TP}/Bedrock/BaseLib/Memory.cpp": "MSVC mem-tracking CRT, _DEBUG only",
    f"{TP}/Bedrock/UtilLib/SocketSSL.cpp": "OpenSSL/WinSock",
    f"{TP}/Bedrock/UtilLib/jsonxx.cpp": "unused",
    f"{TP}/Bedrock/CoRE2/WindowHandler.cpp": "Win32; -> src/platform/window_sdl.cpp",
    # --- D3D9 backend of CoRE2 (dead code in a DX11 project) -------------
    f"{TP}/Bedrock/CoRE2/DX9Device.cpp": "D3D9 backend",
    f"{TP}/Bedrock/CoRE2/DX9Enums.cpp": "D3D9 backend",
    f"{TP}/Bedrock/CoRE2/DX9IndexBuffer.cpp": "D3D9 backend",
    f"{TP}/Bedrock/CoRE2/DX9Shader.cpp": "D3D9 backend",
    f"{TP}/Bedrock/CoRE2/DX9Texture.cpp": "D3D9 backend",
    f"{TP}/Bedrock/CoRE2/DX9VertexBuffer.cpp": "D3D9 backend",
    f"{TP}/Bedrock/CoRE2/DX9VertexFormat.cpp": "D3D9 backend",
    # --- audio: the MVX synth is closed-source 32-bit Windows object code -
    f"{TP}/Phoenix_Tool/Audio/phxSongMVM.cpp": "MVX host, Win32 only",
    f"{TP}/Phoenix_Tool/Audio/phxSongV2M.cpp": "Win32 synth host",
    f"{TP}/Phoenix_Tool/Audio/phxSongWaveSabre.cpp": "Win32 synth host",
    f"{TP}/Phoenix_Tool/Audio/phxSongOGG.cpp": "Win32/DirectSound",
    f"{TP}/Phoenix_Tool/Audio/phxSongBase.cpp": "Win32/DirectSound",
    f"{TP}/Phoenix_Tool/Audio/phxSound.cpp": "Win32/DirectSound",
}

GROUPS = {
    "BASELIB": "Bedrock/BaseLib",
    "UTILLIB": "Bedrock/UtilLib",
    "CORE2": "Bedrock/CoRE2",
    "PHOENIX": "Phoenix",
    "PHOENIX_TOOL": "Phoenix_Tool",
}


def collect(root):
    out = []
    for dirpath, _, files in os.walk(root):
        for f in sorted(files):
            if f.endswith(".cpp"):
                p = os.path.join(dirpath, f).replace("\\", "/")
                if p not in EXCLUDE:
                    out.append(p)
    return sorted(out)


def main():
    groups = {name: collect(f"{TP}/{rel}") for name, rel in GROUPS.items()}

    lines = [
        "# GENERATED by tools/gen_engine_sources.py - do not edit by hand.",
        "#",
        "# The vendored apEx translation units the player compiles.  Every",
        "# exclusion is listed at the bottom with its reason.",
        "",
        "set(APEX_PLATFORM_SOURCES",
        "  src/platform/win32_compat.cpp",
        "  src/platform/stacktracker_posix.cpp",
        "  src/platform/image_stb.cpp",
        "  src/platform/msvc_rand.cpp",
        "  # Every audio back-end is Windows/DirectSound only, so this is the honest",
        "  # 'music unavailable' CphxSound that CapexProject still references.",
        "  src/platform/phxsound_unsupported.cpp",
        "  # The engine window-handle resolver: dependency-free so the D3D11 shim",
        "  # can link it without BaseLib/Logger.",
        "  src/platform/window_handle.cpp",
        "  # GDI subset the text-mesh generator (Mesh.cpp) needs: CoreText on",
        "  # Apple, FreeType everywhere else.  Both emit the same GGO_NATIVE",
        "  # outline records, which is what Mesh.cpp walks.",
        "  $<IF:$<PLATFORM_ID:Darwin>,src/platform/gdi_posix.cpp,src/platform/gdi_freetype.cpp>",
        "  # Globals the unvendored editor UI used to define.",
        "  src/platform/tool_ui_dropped.cpp",
        ")",
        "",
    ]
    for name, files in groups.items():
        lines.append(f"set(APEX_{name}_SOURCES")
        lines += [f"  {f}" for f in files]
        lines += [")", ""]
    lines.append("set(APEX_ENGINE_SOURCES")
    lines += [f"  ${{APEX_{name}_SOURCES}}" for name in groups]
    lines += [")", "", "# Excluded from the build:"]
    lines += [f"#   {p}  -- {why}" for p, why in sorted(EXCLUDE.items())]
    open("cmake/engine_sources.cmake", "w").write("\n".join(lines) + "\n")

    total = sum(len(v) for v in groups.values())
    print(f"wrote cmake/engine_sources.cmake: {total} engine sources")
    for k, v in groups.items():
        print(f"  {k:12s} {len(v):3d}")


if __name__ == "__main__":
    main()
