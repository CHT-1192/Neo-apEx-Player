UINT DXGIFormatBlockSize(DXGI_FORMAT fmt) { return DXGIFormatIsCompressed(fmt) ? 4 : 1; }

UINT DXGIFormatRowPitch(DXGI_FORMAT fmt, UINT width)
{
  const UINT bpp = DXGIFormatBitsPerPixel(fmt);
  if (!bpp) return 0;
  const UINT bs = DXGIFormatBlockSize(fmt);
  const UINT blocks = (width + bs - 1) / bs;
  return (blocks * bpp * bs + 7) / 8;
}

