bool g_warnedUnknownFormat = false;

void WarnUnknownFormat(DXGI_FORMAT fmt, const char *where)
{
  if (g_warnedUnknownFormat) return;
  g_warnedUnknownFormat = true;
  phxvk::LogWarn("unsupported DXGI_FORMAT %d in %s; treating as UNDEFINED (further warnings suppressed)", (int)fmt, where);
}
