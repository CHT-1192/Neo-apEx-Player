// True for the Vk depth / depth-stencil formats this shim maps to.
bool VkFormatIsDepth(VkFormat fmt)
{
  switch (fmt)
  {
  case VK_FORMAT_D16_UNORM:
  case VK_FORMAT_D16_UNORM_S8_UINT:
  case VK_FORMAT_X8_D24_UNORM_PACK32:
  case VK_FORMAT_D24_UNORM_S8_UINT:
  case VK_FORMAT_D32_SFLOAT:
  case VK_FORMAT_D32_SFLOAT_S8_UINT:
    return true;
  default:
    return false;
  }
}

namespace
{
bool FormatUsable(VkFormat fmt, bool needSampled)
{
  if (fmt == VK_FORMAT_UNDEFINED) return false;
  VkFormatProperties props{};
  vkGetPhysicalDeviceFormatProperties(phxvk::Vk().physical, fmt, &props);
  VkFormatFeatureFlags need = VK_FORMAT_FEATURE_DEPTH_STENCIL_ATTACHMENT_BIT;
  if (needSampled) need |= VK_FORMAT_FEATURE_SAMPLED_IMAGE_BIT;
  return (props.optimalTilingFeatures & need) == need;
}

// One warning per (requested -> chosen) pair, not per texture.
bool WarnSubstitution(VkFormat from, VkFormat to)
{
  static VkFormat warnedFrom[8] = {};
  static VkFormat warnedTo[8] = {};
  static int warned = 0;
  for (int i = 0; i < warned; i++)
    if (warnedFrom[i] == from && warnedTo[i] == to) return false;
  if (warned < 8)
  {
    warnedFrom[warned] = from;
    warnedTo[warned] = to;
    warned++;
  }
  return true;
}

const char *FormatName(VkFormat fmt)
{
  switch (fmt)
  {
  case VK_FORMAT_D16_UNORM: return "VK_FORMAT_D16_UNORM";
  case VK_FORMAT_D16_UNORM_S8_UINT: return "VK_FORMAT_D16_UNORM_S8_UINT";
  case VK_FORMAT_X8_D24_UNORM_PACK32: return "VK_FORMAT_X8_D24_UNORM_PACK32";
  case VK_FORMAT_D24_UNORM_S8_UINT: return "VK_FORMAT_D24_UNORM_S8_UINT";
  case VK_FORMAT_D32_SFLOAT: return "VK_FORMAT_D32_SFLOAT";
  case VK_FORMAT_D32_SFLOAT_S8_UINT: return "VK_FORMAT_D32_SFLOAT_S8_UINT";
  default: return "an unsupported format";
  }
}
} // namespace

VkFormat DXGIFormatToVkSupported(DXGI_FORMAT fmt, bool needSampled)
{
  const VkFormat requested = DXGIFormatToVk(fmt);
  if (!VkFormatIsDepth(requested)) return requested;
  if (FormatUsable(requested, needSampled)) return requested;

  // Keep the stencil aspect when the source format had one, then fall back to
  // a depth-only format: MoltenVK on Apple silicon has no 24-bit depth at all,
  // so D24_UNORM_S8_UINT and X8_D24_UNORM_PACK32 are unusable there.
  const bool stencil = (requested == VK_FORMAT_D24_UNORM_S8_UINT || requested == VK_FORMAT_D32_SFLOAT_S8_UINT ||
                        requested == VK_FORMAT_D16_UNORM_S8_UINT);
  const VkFormat candidates[4] = {stencil ? VK_FORMAT_D32_SFLOAT_S8_UINT : VK_FORMAT_D32_SFLOAT, VK_FORMAT_D32_SFLOAT, VK_FORMAT_D16_UNORM,
                                  VK_FORMAT_UNDEFINED};
  for (int i = 0; i < 4 && candidates[i] != VK_FORMAT_UNDEFINED; i++)
  {
    if (!FormatUsable(candidates[i], needSampled)) continue;
    if (WarnSubstitution(requested, candidates[i]))
      phxvk::LogWarn("[d3d11] %s (DXGI_FORMAT %d) is not supported by this device; using %s instead - depth precision or the "
                     "stencil aspect may differ from the D3D11 original",
                     FormatName(requested), (int)fmt, FormatName(candidates[i]));
    return candidates[i];
  }
  phxvk::LogError("[d3d11] no usable depth format for DXGI_FORMAT %d on this device", (int)fmt);
  return requested;
}

VkFormat DXGIFormatToVkView(DXGI_FORMAT viewFormat, VkFormat imageFormat, bool depthAspect, bool stencilAspect)
{
  // A depth/stencil image read through a shader resource view: Vulkan wants
  // the aspect-specific sampling format, which is not always the same as the
  // storage format D3D11 created the texture with.
  if (depthAspect || stencilAspect)
  {
    switch (viewFormat)
    {
    case DXGI_FORMAT_R24_UNORM_X8_TYPELESS:
    case DXGI_FORMAT_R24G8_TYPELESS:
    case DXGI_FORMAT_D24_UNORM_S8_UINT:
      return VK_FORMAT_X8_D24_UNORM_PACK32;
    case DXGI_FORMAT_R32_FLOAT_X8X24_TYPELESS:
    case DXGI_FORMAT_R32G8X24_TYPELESS:
    case DXGI_FORMAT_D32_FLOAT_S8X24_UINT:
      return VK_FORMAT_D32_SFLOAT_S8_UINT;
    default: break;
    }
  }
  return DXGIFormatToVk(viewFormat);
}

